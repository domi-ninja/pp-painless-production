package deploy

import "fmt"

func (d Deployer) ApplyRoutes(plan Plan, bundle Bundle) error {
	for _, host := range bundle.Hosts {
		source := ""
		if host.Routes != "" {
			source = host.RemoteDir + "/routes.caddy"
		}
		if err := d.Runner.SSHScript(d.Root, host.SSH, routeUpdateScript(plan.Config.Project.ResourceID(), source, "/etc/pp/proxy/routes", "/etc/caddy/Caddyfile")); err != nil {
			return fmt.Errorf("host %s routes: %w", host.ID, err)
		}
	}
	return nil
}

// Serialize changes across deployments. Validate a staged full configuration,
// then replace just the owned route file and restore it if reload fails.
func routeUpdateScript(resource, source, routes, caddyfile string) string {
	return `set -eu
umask 077
routes=` + shellQuote(routes) + `
source=` + shellQuote(source) + `
config=` + shellQuote(caddyfile) + `
name=` + shellQuote(resource+".caddy") + `
active="$routes/$name"
[ ! -L "$active" ] || { echo 'route file is a symlink' >&2; exit 1; }
if [ -z "$source" ] && [ ! -e "$active" ]; then exit 0; fi
[ -d "$routes" ] && [ -w "$routes" ]
exec 8>"$routes/../routes.lock"
flock 8
stage=$(mktemp -d "$routes/../pp-routes.XXXXXX")
trap 'rm -rf "$stage"' EXIT HUP INT TERM
mkdir "$stage/routes"
for file in "$routes"/*.caddy; do
 [ -e "$file" ] || continue
 [ ! -L "$file" ] || { echo 'shared route file is a symlink' >&2; exit 1; }
 [ "$(basename "$file")" = "$name" ] || cp "$file" "$stage/routes/"
done
had_old=false
if [ -f "$active" ]; then cp "$active" "$stage/previous"; had_old=true; fi
if [ -n "$source" ]; then cp "$source" "$stage/routes/$name"; fi
# The supplied host setup uses this one absolute import. Keep other imports absolute.
line="import $routes/*.caddy"
grep -Fqx "$line" "$config" || { echo 'Caddyfile must import the pp routes directory on its own line' >&2; exit 1; }
# paths are generated by pp, never supplied by the app config.
awk -v old="$line" -v new="import $stage/routes/*.caddy" '{if ($0 == old) print new; else print}' "$config" > "$stage/Caddyfile"
caddy validate --adapter caddyfile --config "$stage/Caddyfile"
if [ -n "$source" ]; then
 install -m 0644 "$source" "$routes/../$name.next"
 mv "$routes/../$name.next" "$active"
else rm -f "$active"; fi
if ! caddy reload --adapter caddyfile --config "$config"; then
 if [ "$had_old" = true ]; then
  install -m 0644 "$stage/previous" "$routes/../$name.next"
  mv "$routes/../$name.next" "$active"
 else rm -f "$active"; fi
 caddy reload --adapter caddyfile --config "$config" || { echo 'failed to reload restored Caddy configuration; inspect Caddy before retrying' >&2; exit 1; }
 echo 'Caddy reload failed; restored the previous route file' >&2
 exit 1
fi
`
}

func (d Deployer) checkRemovedHosts(plan Plan, state State) error {
	if state.CurrentReleaseID == "" {
		return nil
	}
	record, err := LoadRelease(d.Root, plan.Config.Project, state.CurrentReleaseID)
	if err != nil {
		return err
	}
	selected := map[string]bool{}
	for _, host := range plan.Hosts {
		selected[host.SSH] = true
	}
	for _, host := range record.Hosts {
		if selected[host.SSH] {
			continue
		}
		if err := validateSSHTarget(host.SSH); err != nil {
			return err
		}
		command := "docker ps -aq --filter " + shellQuote("label=pp.project="+record.Project) + " --filter " + shellQuote("label=pp.environment="+record.Environment)
		ids, err := d.Runner.Output(d.Root, "ssh", host.SSH, command)
		if err != nil {
			return fmt.Errorf("inspect removed host %s: %w", host.ID, err)
		}
		if ids != "" {
			return fmt.Errorf("removed host %s still has owned containers; run pp down with its saved deployment first", host.ID)
		}
		if err := d.Runner.SSHScript(d.Root, host.SSH, routeUpdateScript(plan.Config.Project.ResourceID(), "", "/etc/pp/proxy/routes", "/etc/caddy/Caddyfile")); err != nil {
			return err
		}
	}
	return nil
}
